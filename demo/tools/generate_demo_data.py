def render_receipt(spec: dict) -> Image.Image:
    w = 560
    h = 300 + 46 * len(spec["items"])
    img = Image.new("RGB", (w, h), (244, 243, 238))
    d = ImageDraw.Draw(img)

    f_title, f_body, f_small = font(34), font(24), font(19)
    y = 30
    d.text((w // 2, y), spec["store"], font=f_title, fill=(30, 30, 30), anchor="ma")
    y += 48
    d.text((w // 2, y), spec["biz"], font=f_small, fill=(90, 90, 90), anchor="ma")
    y += 32
    d.text((w // 2, y), spec["date"], font=f_small, fill=(90, 90, 90), anchor="ma")
    y += 40
    d.line([(30, y), (w - 30, y)], fill=(160, 160, 160), width=2)
    y += 20

    for name, qty, amount in spec["items"]:
        d.text((36, y), name, font=f_body, fill=(30, 30, 30))
        d.text((w - 36, y), f"{qty}   {amount}", font=f_body, fill=(30, 30, 30), anchor="ra")
        y += 46

    d.line([(30, y), (w - 30, y)], fill=(160, 160, 160), width=2)
    y += 22
    d.text((36, y), "합계", font=f_body, fill=(0, 0, 0))
    d.text((w - 36, y), f"{spec['total']} 원", font=f_title, fill=(0, 0, 0), anchor="ra")
    y += 56
    d.text((36, y), spec["pay"], font=f_small, fill=(90, 90, 90))
    y += 30
    d.text((36, y), "* 본 영수증은 시연용 예제입니다.", font=f_small, fill=(150, 150, 150))

    # 휴대폰으로 찍은 사진 느낌: 살짝 기울이고 여백을 준다
    img = img.rotate(-1.4, expand=True, fillcolor=(228, 226, 220))
    if spec["blur"]:
        img = img.filter(ImageFilter.GaussianBlur(spec["blur"]))
    return img


def build_receipts() -> None:
    out = DEMO / "02_영수증정산" / "영수증"
    out.mkdir(parents=True, exist_ok=True)
    for spec in RECEIPTS:
        render_receipt(spec).save(out / spec["file"])
        print(f"  02_영수증정산/영수증/{spec['file']}")
    render_receipt(KTX_RECEIPT).convert("RGB").save(
        out / KTX_RECEIPT["file"], "PDF", resolution=110
    )
    print(f"  02_영수증정산/영수증/{KTX_RECEIPT['file']}")


